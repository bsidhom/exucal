import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseAst, type Plugin, type ResolvedConfig } from "vite";

/**
 * Builds the service worker and tells it what to cache.
 *
 * The plugin adds `src/sw.ts` as a second entry point of the production
 * build, emitted unhashed as `sw.js` at the root of the output so that its
 * scope covers the whole site. Once the rest of the bundle is known, it
 * prepends a `__PRECACHE__` constant to the worker's code listing the URL of
 * every file in the build (the page, the hashed scripts and styles, and the
 * static assets copied from `public/`), except those `options.exclude`
 * rules out, along with a version derived from the contents of all of them.
 * Any change to the build therefore changes `sw.js`, which is what makes
 * browsers install the update.
 */
export function precache(options: PrecacheOptions = {}): Plugin {
  const exclude = options.exclude ?? (() => false);
  const swEntry = "sw";
  const swFileName = `${swEntry}.js`;
  let config: ResolvedConfig;

  return {
    name: "precache",
    apply: "build",
    // Run after Vite's own build plugins so that `index.html` has been added
    // to the bundle by the time `generateBundle` runs.
    enforce: "post",
    config: () => ({
      build: {
        rollupOptions: {
          input: { index: "index.html", [swEntry]: "src/sw.ts" },
          output: {
            entryFileNames: (chunk) =>
              chunk.name === swEntry ? swFileName : "assets/[name]-[hash].js",
          },
        },
      },
    }),
    configResolved(resolved) {
      config = resolved;
    },
    generateBundle(_options, bundle) {
      const sw = bundle[swFileName];
      if (sw?.type !== "chunk") {
        this.error(
          `Expected the bundle to contain the service worker chunk ${swFileName}.`,
        );
      }

      // Every file the build consists of, other than the worker itself, keyed
      // by the path it will be served from and mapped to its contents.
      const files = new Map<string, string | Uint8Array>();
      for (const [fileName, output] of Object.entries(bundle)) {
        if (fileName !== swFileName && !exclude(fileName)) {
          files.set(
            fileName,
            output.type === "chunk" ? output.code : output.source,
          );
        }
      }
      for (const fileName of listFiles(config.publicDir)) {
        if (!exclude(fileName)) {
          files.set(fileName, readFileSync(join(config.publicDir, fileName)));
        }
      }

      const hash = createHash("sha256");
      const urls: string[] = [];
      for (const fileName of [...files.keys()].sort()) {
        hash
          .update(fileName)
          .update("\0")
          .update(files.get(fileName)!)
          .update("\0");
        // The page is served from the site root, not from `/index.html`.
        urls.push(
          fileName === "index.html"
            ? config.base
            : config.base + encodePath(fileName),
        );
      }
      const manifest = { version: hash.digest("hex").slice(0, 16), urls };

      sw.code = injectManifest(manifest, sw.code);
    },
  };
}

export interface PrecacheOptions {
  /**
   * Returns whether to leave a file out of the precache, given its path
   * relative to the output root with `/` separators (`icons/icon.svg`). Left
   * out files are still built and served; they are just fetched from the
   * network when requested rather than downloaded up front, and changing
   * them does not produce a new service worker.
   */
  exclude?: (fileName: string) => boolean;
}

/** What the service worker's `__PRECACHE__` constant holds. */
export interface PrecacheManifest {
  version: string;
  urls: string[];
}

/** The name of the constant that holds the manifest in the service worker. */
const manifestName = "__PRECACHE__";

/**
 * Returns `code` with a statement prepended that defines the manifest.
 *
 * The statement is generated by serializing the manifest with
 * `JSON.stringify`, whose output is always a valid JavaScript expression
 * (JSON has been a strict subset of ECMAScript since ES2019): every string is
 * emitted as a quoted literal with `"`, `\` and control characters escaped,
 * so no file name can end its literal early and be read as code. The
 * statement ends up in a script that every visitor runs, so that reasoning is
 * checked rather than trusted, before and after the fact:
 *
 * - Before, the manifest is validated: the version must be a hex string, and
 *   every URL must be a root-relative path made only of the characters that
 *   `encodeURIComponent` leaves as they are, `/` and percent-escapes, which
 *   `encodePath` guarantees for any file name.
 * - After, the result is parsed with Vite's own JavaScript parser and rejected
 *   unless its first statement is a `const` declaration of the manifest whose
 *   initializer is a literal made only of plain objects, arrays and strings.
 *   This proves that the prepended statement contains no code, and that the
 *   worker as a whole still parses.
 */
export function injectManifest(
  manifest: PrecacheManifest,
  code: string,
): string {
  if (!/^[0-9a-f]{16}$/.test(manifest.version)) {
    throw new Error(
      `Invalid precache version: ${JSON.stringify(manifest.version)}`,
    );
  }
  for (const url of manifest.urls) {
    if (!/^\/(?:[A-Za-z0-9\-._~!*'()/]|%[0-9A-F]{2})*$/.test(url)) {
      throw new Error(`Invalid precache URL: ${JSON.stringify(url)}`);
    }
  }

  const statement = `const ${manifestName} = ${JSON.stringify(manifest)};`;
  const result = `${statement}\n${code}`;

  const [first] = parseAst(result, { sourceType: "module" }).body;
  const isManifestDeclaration =
    first?.type === "VariableDeclaration" &&
    first.kind === "const" &&
    first.declarations.length === 1 &&
    first.declarations[0]!.id.type === "Identifier" &&
    first.declarations[0]!.id.name === manifestName &&
    first.declarations[0]!.init !== null &&
    isDataLiteral(first.declarations[0]!.init);
  if (!isManifestDeclaration) {
    throw new Error(
      `The generated ${manifestName} statement is not a plain data literal: ${statement}`,
    );
  }
  return result;
}

/** An expression node of the syntax tree that `parseAst` returns. */
export type Expression = NonNullable<
  Extract<
    ReturnType<typeof parseAst>["body"][number],
    { type: "VariableDeclaration" }
  >["declarations"][number]["init"]
>;

/**
 * Whether `node` is a literal built only from plain objects with fixed keys,
 * arrays and strings, so that evaluating it can never run code.
 */
export function isDataLiteral(node: Expression): boolean {
  switch (node.type) {
    case "Literal":
      return typeof node.value === "string";
    case "ArrayExpression":
      return node.elements.every(
        (element) =>
          element !== null &&
          element.type !== "SpreadElement" &&
          isDataLiteral(element),
      );
    case "ObjectExpression":
      return node.properties.every(
        (property) =>
          property.type === "Property" &&
          property.kind === "init" &&
          !property.computed &&
          !property.method &&
          !property.shorthand &&
          (property.key.type === "Identifier" ||
            (property.key.type === "Literal" &&
              typeof property.key.value === "string")) &&
          isDataLiteral(property.value),
      );
    default:
      return false;
  }
}

/**
 * Percent-encodes each segment of a `/`-separated relative path so that it can
 * be appended to a URL, leaving `/` itself intact.
 */
function encodePath(path: string): string {
  return path.split("/").map(encodeURIComponent).join("/");
}

/** The paths of every file under `dir`, relative to it, using `/` separators. */
function listFiles(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) =>
      relative(dir, join(entry.parentPath, entry.name)).replaceAll("\\", "/"),
    );
}
